/**
 * 全仓共用的枚举：把此前散落在各文件里的「魔法数字 / 魔法字符串」收成一处。
 *
 * 为什么要有这个文件：判定状态 0/1/2/3 在 7.162 与 7.164 两轮各丢过一次维度 ——
 * 症状相同：某个跨层传值的点写死了 `2`，把 `dead`(3，硬排除) 静默降级成 `blocked`(2，×6 降权)，
 * 一条连不上的中继于是继续占着 `connect()` 名额。裸数字读不出这层语义，改一行的代价
 * 看起来是「等价重写」，而单测与类型都拦不住。用枚举之后，比较处读作 `St.Dead`，
 * 传错层会被 `tsc` 抓住（`St` 是值也是类型）。
 *
 * 为什么同时导出 `StLike` / `ModeLike`：仓库里还有几十处调用点按数字（`2`）或字符串
 * （`"lat"`）传参，一次性改成枚举成员会把改动面扩到整仓 —— 那一轮的 diff 就不再是
 * 「修一条缺陷」，而是一次无法逐行复核的重构。所以参数类型保留宽松的联合类型，
 * 只有**产生**与**比较**的地方用枚举。
 */

/** 判定状态：0 未知 / 1 可用 / 2 被拦 / 3 连不上 */
export enum St {
  Unknown = 0,
  Ok = 1,
  Blocked = 2,
  Dead = 3,
}

/** 判定状态的宽松写法（兼容既有按数字传参的调用点与老数据） */
export type StLike = St | 0 | 1 | 2 | 3;

/** 传输模式：吞吐优先 / 延迟优先 */
export enum Mode {
  Tput = "tput",
  Lat = "lat",
}

/** 传输模式的宽松写法（兼容既有按字符串传参的调用点与 `?mode=` 参数） */
export type ModeLike = Mode | "tput" | "lat";

